def clean_gdp(val):
    if isinstance(val, str):
        val = val.replace("$", "")
        val = val.replace("-", "")
        if "Tn" in val:
            return float(val.replace(" Tn", "")) * 1e12
        elif "Bn" in val:
            return float(val.replace(" Bn", "")) * 1e9
        elif "Mn" in val:
            return float(val.replace(" Mn", "")) * 1e6
        elif "Th" in val:
            return float(val.replace(" Th", "")) * 1e3
    return val

